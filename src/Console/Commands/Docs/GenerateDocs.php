<?php

namespace RCV\Core\Console\Commands\Docs;

use Illuminate\Console\Command;

class GenerateDocs extends Command
{
    protected $signature = 'module:docs {--output=docs}';

    protected $description = 'Generate basic module documentation stubs';

    public function handle(): int
    {
        $output = base_path($this->option('output'));
        if (! is_dir($output)) {
            if (! mkdir($output, 0755, true) && ! is_dir($output)) {
                $this->error("Unable to create documentation directory: {$output}");

                return self::FAILURE;
            }
        }
        if (file_put_contents($output.'/README.md', "# Module Documentation\n\nGenerated by module:docs\n") === false) {
            $this->error("Unable to write documentation in: {$output}");

            return self::FAILURE;
        }
        $this->info("Documentation generated at {$output}");

        return self::SUCCESS;
    }
}
